import fs from 'node:fs';
import { presets } from '../src/contexts/appearance-config.js';

// Regenerate after editing presets. Both early page paint and React share these defaults.
let css = '/* Generated by scripts/generate-appearance.mjs. Edit appearance-config.js. */\n';
for (const preset of presets) for (const mode of ['light', 'dark']) {
  const [background, card, primary] = preset[mode];
  const dark = mode === 'dark';
  const foreground = dark ? '#EAF0FA' : '#17243B';
  const muted = dark ? '#26354B' : '#EDF1F7';
  const tokens = {
    background, card, popover: card, foreground, 'card-foreground': foreground, 'popover-foreground': foreground,
    primary, 'primary-foreground': dark ? '#081426' : '#FFFFFF', secondary: muted, 'secondary-foreground': foreground,
    muted, 'muted-foreground': dark ? '#AEBCD2' : '#55657C', accent: muted, 'accent-foreground': primary,
    border: dark ? '#344760' : '#DAE2ED', input: dark ? '#657C9C' : '#7C8DA6', ring: dark ? '#ABC5FF' : '#245CFA',
    sidebar: dark ? '#081426' : '#0A1C36', 'sidebar-foreground': '#D6E1F3', 'sidebar-accent': '#1A3355',
    'sidebar-accent-foreground': '#FFFFFF', 'sidebar-border': '#263E5E', 'sidebar-primary': '#91B5FF',
    'sidebar-primary-foreground': '#081426', 'sidebar-ring': '#A8C5FF',
    'chart-1': primary, 'chart-2': dark ? '#77C9B0' : '#287D68', 'chart-3': dark ? '#F1C67C' : '#AD7626',
    'chart-4': dark ? '#B6ADFA' : '#8275C1', 'chart-5': dark ? '#EEA6B0' : '#C26E7C',
    success: dark ? '#80D9B5' : '#146345', 'success-soft': dark ? '#183F35' : '#E5F3EC',
    warning: dark ? '#F2CF8A' : '#805400', 'warning-soft': dark ? '#453A25' : '#FFF2D7',
    destructive: dark ? '#FFA8B7' : '#B6243D', 'danger-soft': dark ? '#472C3A' : '#FFEBEF',
    'info-soft': dark ? '#203B60' : '#E9F0FD',
  };
  css += `html[data-preset="${preset.id}"][data-mode="${mode}"] {\n${Object.entries(tokens).map(([key,value])=>`  --${key}: ${value};`).join('\n')}\n  color-scheme: ${mode};\n}\n`;
}
fs.writeFileSync('src/styles/appearance-tokens.css', css);
const config = fs.readFileSync('src/contexts/appearance-config.js', 'utf8').replace(/export /g, '');
const helpers = fs.readFileSync('src/contexts/appearance-utils.js', 'utf8').replace(/^import .*;\n/m, '').replace(/export /g, '');
const init = `/* Generated. Uses presentation storage only. */\n(function(){\n${config}\n${helpers}\ntry {
  const p = readAppearance();
  const mode = p.appearance === 'system' ? (matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light') : p.appearance;
  const presetId = mode === 'dark' ? p.darkPreset : p.lightPreset;
  const root = document.documentElement;
  root.classList.toggle('dark', mode === 'dark');
  Object.assign(root.dataset, {mode, preset:presetId, density:p.density, tableDensity:p.tableDensity, radius:p.radius,
    scale:p.fontScale, motion:p.motion, intensity:p.animationIntensity, sidebarStyle:p.sidebarStyle,
    sidebarDensity:p.sidebarDensity, cardStyle:p.cardStyle, surface:p.surfaceStyle});
  if(p.customAccent) {
    const accent = accessibleAccent(p.customAccent, presets.find(x=>x.id===presetId)[mode][1]);
    root.style.setProperty('--primary',accent); root.style.setProperty('--ring',accent);
    root.style.setProperty('--sidebar-primary',accent);root.style.setProperty('--primary-foreground',accentForeground(accent));
  }
} catch { /* Storage or matchMedia may be unavailable. Use CSS defaults. */ }
})();\n`;
fs.writeFileSync('public/appearance-init.js', init);
console.log('Generated nine light/dark palettes and the shared pre-paint appearance initializer.');
