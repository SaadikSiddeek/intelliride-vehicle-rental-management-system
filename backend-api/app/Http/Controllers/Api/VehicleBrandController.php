<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use Illuminate\Database\Eloquent\ModelNotFoundException;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Facades\Validator;
use Illuminate\Support\Str;
use Illuminate\Validation\Rule;

class VehicleBrandController extends Controller
{
    private const TABLE = 'vehicle_brand_tb';
    private const IMAGE_DISK = 'vehicle_brands';

    // ================= IMAGE FUNCTIONALITY: HELPERS =================

    private function brandFolder(string $brandName, int $id): string
    {
        $slug = Str::slug($brandName);

        return ($slug !== '' ? $slug : 'brand') . '_' . $id;
    }

    private function managedImagePath(?string $path): bool
    {
        if (!$path) {
            return false;
        }

        // Accept only paths generated by this controller.
        // Prevent arbitrary filesystem paths from being served/deleted.
        return preg_match(
            '/\A[a-z0-9-]+_[1-9][0-9]*\/[a-f0-9-]{36}\.(jpg|jpeg|png|webp)\z/',
            $path
        ) === 1;
    }

    private function imageUrl(?string $path): ?string
    {
        if (!$this->managedImagePath($path)) {
            return null;
        }

        return url('/api/vehicle-brand-images/' . $path);
    }

    private function formatBrand(object $brand): array
    {
        return [
            'ID' => $brand->ID,
            'id' => $brand->ID,
            'brand_name' => $brand->brand_name,
            'country' => $brand->country ?? '',
            'logo' => $brand->logo,
            'logo_url' => $this->imageUrl($brand->logo),
            'status' => (int) $brand->status,
        ];
    }

    private function deleteImageSafely(?string $path): void
    {
        if (!$this->managedImagePath($path)) {
            return;
        }

        try {
            Storage::disk(self::IMAGE_DISK)->delete($path);

            // Do not delete the whole directory:
            // another request may have uploaded a newer file there.
        } catch (\Throwable $th) {
            // A cleanup failure must not reverse a committed database save.
            report($th);
        }
    }

    // ================= CREATE / UPDATE =================

    public function saveVehicleBrand(Request $request)
    {
        $newImagePath = null;
        $oldImagePath = null;
        $committed = false;

        try {
            $idValidator = Validator::make($request->all(), [
                'upd_id' => ['nullable', 'integer', 'min:1'],
            ]);

            if ($idValidator->fails()) {
                return response()->json([
                    'status' => false,
                    'errors' => $idValidator->errors(),
                ], 422);
            }

            $updateId = $request->input('upd_id');
            $existingBrand = null;

            if ($updateId !== null && $updateId !== '') {
                $existingBrand = DB::table(self::TABLE)
                    ->where('ID', $updateId)
                    ->first(['ID']);

                if (!$existingBrand) {
                    return response()->json([
                        'status' => false,
                        'message' => 'Vehicle brand not found.',
                    ], 404);
                }
            }

            $isUpdate = $existingBrand !== null;

            $brandNameRule = Rule::unique(self::TABLE, 'brand_name');

            if ($isUpdate) {
                $brandNameRule->ignore($existingBrand->ID, 'ID');
            }

            $validator = Validator::make(
                $request->all(),
                [
                    'brand_name' => [
                        'required',
                        'string',
                        'max:100',
                        $brandNameRule,
                    ],
                    'country' => [
                        'nullable',
                        'string',
                        'max:100',
                    ],
                    'status' => ['required', 'boolean'],

                    // IMAGE FUNCTIONALITY: validate real image uploads.
                    'logo' => [
                        'nullable',
                        'image',
                        'mimes:jpg,jpeg,png,webp',
                        'max:2048',
                        'dimensions:max_width=6000,max_height=6000',
                    ],

                    // IMAGE FUNCTIONALITY: explicit saved-logo removal.
                    'remove_logo' => ['sometimes', 'boolean'],
                ],
                [
                    'brand_name.required' => 'Brand name is required.',
                    'brand_name.unique' => 'This vehicle brand already exists.',
                    'brand_name.max' => 'Brand name cannot exceed 100 characters.',
                    'country.max' => 'Country cannot exceed 100 characters.',
                    'logo.image' => 'Please upload a valid image.',
                    'logo.mimes' => 'Logo must be JPG, PNG or WebP.',
                    'logo.max' => 'Logo must not exceed 2 MB.',
                    'logo.dimensions' => 'Logo dimensions must not exceed 6000 × 6000 pixels.',
                ]
            );

            if ($validator->fails()) {
                return response()->json([
                    'status' => false,
                    'errors' => $validator->errors(),
                ], 422);
            }

            $validated = $validator->validated();

            $brand = DB::transaction(function () use (
                $request,
                $validated,
                $isUpdate,
                $existingBrand,
                &$newImagePath,
                &$oldImagePath
            ) {
                if ($isUpdate) {
                    // Serialize updates to the same brand.
                    $current = DB::table(self::TABLE)
                        ->where('ID', $existingBrand->ID)
                        ->lockForUpdate()
                        ->first();

                    if (!$current) {
                        throw new ModelNotFoundException();
                    }

                    $brandId = (int) $current->ID;
                    $oldImagePath = $current->logo;
                } else {
                    // IMAGE FUNCTIONALITY:
                    // Insert FIRST to obtain the actual auto-increment ID.
                    $brandId = DB::table(self::TABLE)->insertGetId([
                        'brand_name' => $validated['brand_name'],
                        'country' => $validated['country'] ?? null,
                        'logo' => null,
                        'status' => (int) $validated['status'],
                        'created_at' => now(),
                        'updated_at' => now(),
                    ], 'ID');
                }

                $logoPath = $oldImagePath;

                // IMAGE FUNCTIONALITY:
                // Example directory: toyota_12
                $folder = $this->brandFolder(
                    $validated['brand_name'],
                    (int) $brandId
                );

                $disk = Storage::disk(self::IMAGE_DISK);

                if ($request->hasFile('logo')) {
                    // IMAGE FUNCTIONALITY: upload or replace.
                    // Generate filename; never trust the original filename.
                    $file = $request->file('logo');
                    $filename = Str::uuid()->toString()
                        . '.'
                        . $file->extension();

                    // Assign before writing so failed partial writes
                    // can also be cleaned up.
                    $newImagePath = $folder . '/' . $filename;

                    $disk->putFileAs($folder, $file, $filename);

                    $logoPath = $newImagePath;
                } elseif ($request->boolean('remove_logo')) {
                    // IMAGE FUNCTIONALITY: remove without replacement.
                    $logoPath = null;
                } elseif (
                    $this->managedImagePath($oldImagePath) &&
                    dirname($oldImagePath) !== $folder
                ) {
                    // IMAGE FUNCTIONALITY:
                    // Brand renamed without selecting a new image.
                    // Copy into the new brand-name_ID folder first.
                    if (!$disk->exists($oldImagePath)) {
                        throw new \RuntimeException(
                            'Existing brand image is missing.'
                        );
                    }

                    $filename = Str::uuid()->toString()
                        . '.'
                        . pathinfo($oldImagePath, PATHINFO_EXTENSION);

                    $newImagePath = $folder . '/' . $filename;

                    $disk->copy($oldImagePath, $newImagePath);

                    $logoPath = $newImagePath;
                }

                DB::table(self::TABLE)
                    ->where('ID', $brandId)
                    ->update([
                        'brand_name' => $validated['brand_name'],
                        'country' => $validated['country'] ?? null,
                        'logo' => $logoPath,
                        'status' => (int) $validated['status'],
                        'updated_at' => now(),
                    ]);

                return DB::table(self::TABLE)
                    ->where('ID', $brandId)
                    ->first();
            });

            $committed = true;

            // IMAGE FUNCTIONALITY:
            // Delete the old image only AFTER the database commits.
            if ($oldImagePath && $oldImagePath !== $brand->logo) {
                $this->deleteImageSafely($oldImagePath);
            }

            return response()->json([
                'status' => true,
                'data' => $this->formatBrand($brand),
                'message' => $isUpdate
                    ? 'Vehicle brand updated successfully.'
                    : 'Vehicle brand created successfully.',
            ], $isUpdate ? 200 : 201);
        } catch (ModelNotFoundException $th) {
            return response()->json([
                'status' => false,
                'message' => 'Vehicle brand not found.',
            ], 404);
        } catch (\Throwable $th) {
            // IMAGE FUNCTIONALITY:
            // Database rollback does not undo filesystem writes.
            if (!$committed && $newImagePath) {
                $this->deleteImageSafely($newImagePath);
            }

            report($th);

            return response()->json([
                'status' => false,
                'message' => 'Unable to save vehicle brand. Please try again.',
            ], 500);
        }
    }

    // ================= GET TABLE RECORDS =================

    public function getVehicleBrands(Request $request)
    {
        try {
            $brands = DB::table(self::TABLE)
                ->orderByDesc('ID')
                ->get([
                    'ID',
                    'brand_name',
                    'country',
                    'logo',
                    'status',
                ]);

            return response()->json([
                'status' => true,
                'data' => $brands->map(
                    fn($brand) => $this->formatBrand($brand)
                ),
                'message' => 'Vehicle brands retrieved successfully.',
            ], 200);
        } catch (\Throwable $th) {
            report($th);

            return response()->json([
                'status' => false,
                'message' => 'Unable to load vehicle brands. Please try again.',
            ], 500);
        }
    }

    // ================= FETCH FOR EDIT =================

    public function fetchVehicleBrandData(Request $request)
    {
        try {
            $validator = Validator::make($request->all(), [
                'upd_id' => ['required', 'integer', 'min:1'],
            ]);

            if ($validator->fails()) {
                return response()->json([
                    'status' => false,
                    'errors' => $validator->errors(),
                ], 422);
            }

            $brand = DB::table(self::TABLE)
                ->where('ID', $validator->validated()['upd_id'])
                ->first([
                    'ID',
                    'brand_name',
                    'country',
                    'logo',
                    'status',
                ]);

            if (!$brand) {
                return response()->json([
                    'status' => false,
                    'message' => 'Vehicle brand not found.',
                ], 404);
            }

            return response()->json([
                'status' => true,
                'data' => $this->formatBrand($brand),
                'message' => 'Vehicle brand retrieved successfully.',
            ], 200);
        } catch (\Throwable $th) {
            report($th);

            return response()->json([
                'status' => false,
                'message' => 'Unable to fetch vehicle brand. Please try again.',
            ], 500);
        }
    }

    // ================= IMAGE FUNCTIONALITY: DISPLAY IMAGE =================

    public function showLogo(string $folder, string $filename)
    {
        $path = $folder . '/' . $filename;

        abort_unless($this->managedImagePath($path), 404);

        $disk = Storage::disk(self::IMAGE_DISK);

        abort_unless($disk->exists($path), 404);

        return response()->file($disk->path($path), [
            'X-Content-Type-Options' => 'nosniff',
            'Cache-Control' => 'public, max-age=3600',
        ]);
    }
}
